	/**
	 * Emit real @media rules for a block's tablet/mobile overrides. Rules are
	 * scoped to the block root with a data attribute, so repeated blocks
	 * (e.g. product cards) reuse one stylesheet rule set. The media cascade reproduces
	 * inheritance: mobile viewports also receive the tablet block.
	 *
	 * @param string $type     Block type.
	 * @param string $html     Rendered block HTML.
	 * @param array  $settings Sanitized settings.
	 * @return string
	 */
	public static function apply_responsive( $type, $html, $settings ) {
		if ( '' === $html || ! is_array( $settings ) ) {
			return $html;
		}

		$inner   = self::responsive_inner_map();
		$entries = isset( $inner[ $type ] ) ? $inner[ $type ] : array();
		$generic = true;
		foreach ( $entries as $entry ) {
			if ( isset( $entry['root_unprefixed'] ) && false === $entry['root_unprefixed'] ) {
				$generic = false;
			}
		}

		// Collect tablet/mobile declarations per device.
		$devices = array();
		foreach ( array( 'tablet', 'mobile' ) as $device ) {
			$rules = array(); // selector => list of declarations.

			if ( $generic ) {
				// Root element rules (first tag carries the token) for plain
				// unprefixed keys.
				$decls = array();
				foreach ( array_keys( self::responsive_root_keys() ) as $key ) {
					$variant = $device . '_' . $key;
					if ( ! isset( $settings[ $variant ] ) ) {
						continue;
					}
					// 'align' means text-align on text-style widgets but box
					// alignment / placement on these — never emit text-align.
					if ( 'align' === $key && in_array( $type, array( 'xcosb/gb-container', 'xcosb/cc-cart', 'xcosb/cc-cart-items', 'xcosb/cc-cart-totals', 'xcosb/cc-checkout', 'xcosb/cc-checkout-contact', 'xcosb/cc-checkout-billing', 'xcosb/cc-checkout-shipping', 'xcosb/cc-checkout-notes', 'xcosb/cc-checkout-totals', 'xcosb/cc-checkout-payment' ), true ) ) {
						continue;
					}
					$value = self::responsive_css_value( $key, $settings[ $variant ] );
					if ( '' !== $value ) {
						// !important: the desktop value lives inline on this element.
						$decls[] = self::css_key_to_prop( $key ) . ':' . $value . ' !important';
					}
				}
				if ( ! empty( $decls ) ) {
					$rules['[data-xsb-r="{TOKEN}"]'] = $decls;
				}

				// CSS transform group (composite): the root element carries the
				// unprefixed keys, so a device override of transform_type emits
				// one rule with the full transform + origin built from that
				// device's own offset/scale/rotate values.
				if ( isset( $settings[ $device . '_transform_type' ] ) ) {
					$tdecls = self::transform_css_decls( $settings, $device, '' );
					if ( ! empty( $tdecls ) ) {
						$tdecls_imp = array();
						foreach ( $tdecls as $td ) {
							$tdecls_imp[] = $td . ' !important';
						}
						$token_sel = '[data-xsb-r="{TOKEN}"]';
						$rules[ $token_sel ] = array_merge(
							isset( $rules[ $token_sel ] ) ? $rules[ $token_sel ] : array(),
							$tdecls_imp
						);
					}
				}
			}			// Banner backgrounds/overlay/placement compose as one unit per
				// device (the renderer builds one inline background string).
				if ( 'xcosb/gb-banner' === $type ) {
					self::banner_responsive_rules( $rules, $device, $settings );
				}
				// Cart / checkout boxes: 'align' is placement (margins), so it
				// needs real margin rules, not text-align.
				if ( in_array( $type, array( 'xcosb/cc-cart', 'xcosb/cc-cart-items', 'xcosb/cc-cart-totals', 'xcosb/cc-checkout', 'xcosb/cc-checkout-contact', 'xcosb/cc-checkout-billing', 'xcosb/cc-checkout-shipping', 'xcosb/cc-checkout-notes', 'xcosb/cc-checkout-totals', 'xcosb/cc-checkout-payment' ), true ) ) {
					self::cc_placement_rules( $rules, $device, $settings );
				}

				// Inner element rules from the per-type map.
				foreach ( $entries as $entry ) {
					// Whole-grid reflow (grid-template-columns repeat N).
			if ( ! empty( $entry['grid'] ) ) {
				$variant = $device . '_' . $entry['grid']['variant'];
				if ( isset( $settings[ $variant ] ) ) {
					$value = self::responsive_value_of( 'cols', $settings[ $variant ] );
					if ( '' !== $value ) {
						$rules[ self::responsive_selector_patterns( $entry['grid']['selector'] ) ] = array(
							'grid-template-columns:' . $value . ' !important',
						);
					}
				}
			}
			// Flex-grid reflow for the WooCommerce product list (item widths).
			if ( ! empty( $entry['itemWidths'] ) ) {
				$variant = $device . '_' . $entry['itemWidths']['variant'];
				if ( isset( $settings[ $variant ] ) ) {
					$n     = min( 6, max( 1, absint( $settings[ $variant ] ) ) );
					$gaps  = 20 * ( $n - 1 );
					$rules[ self::responsive_selector_patterns( $entry['itemWidths']['selector'] ) ] = array(
						'width:calc((100% - ' . $gaps . 'px) / ' . $n . ') !important',
					);
				}
			}
			// Container column spans: one nth-child rule per override.
			if ( ! empty( $entry['spans'] ) ) {
				$variant = $device . '_' . $entry['spans']['variant'];
				if ( isset( $settings[ $variant ] ) && is_array( $settings[ $variant ] ) ) {
					foreach ( array_values( $settings[ $variant ] ) as $idx => $span ) {
						$span = absint( $span );
						if ( $span < 1 || $span > 12 ) {
							continue;
						}
						// Suffix binds to every selector variant (see helper).
						$selector = self::responsive_selector_patterns( $entry['spans']['selector'], ':nth-child(' . ( $idx + 1 ) . ')' );
						$rules[ $selector ] = array(
							'grid-column:auto / span ' . $span . ' !important',
						);
					}
				}
			}
			// Container per-column styles: device overrides live inside each
			// column_styles row (tablet_background, mobile_padding_top, …) and
			// emit one nth-child rule per column that has a variant — scoped
			// to the block token so repeated containers never collide.
			if ( ! empty( $entry['colStyles'] ) ) {
				$rows = ( isset( $settings['column_styles'] ) && is_array( $settings['column_styles'] ) )
					? array_values( $settings['column_styles'] )
					: array();
				foreach ( $rows as $idx => $row ) {
					if ( ! is_array( $row ) ) {
						continue;
					}
					$decls = array();
					$flex  = false;
					foreach ( self::column_style_responsive_defs() as $key => $def ) {
						$rk = $device . '_' . $key;
						if ( ! array_key_exists( $rk, $row ) || '' === $row[ $rk ] ) {
							continue;
						}
						if ( isset( $def['flex'] ) ) {
							// Content alignment: translate the friendly value to
							// the flex keyword the renderer uses, and mirror its
							// text-align for align_h (needed to override a wider
							// device's inline text-align).
							$stored = $row[ $rk ];
							if ( ! isset( $def['map'][ $stored ] ) ) {
								continue;
							}
							$flex    = true;
							$decls[] = $def['flex'] . ':' . $def['map'][ $stored ] . ' !important';
							if ( 'align_h' === $key ) {
								$decls[] = 'text-align:' . $stored . ' !important';
							}
							continue;
						}
						$value = self::responsive_value_of( $def['type'], $row[ $rk ] );
						if ( '' === $value ) {
							continue;
						}
						$decls[] = $def['prop'] . ':' . $value . ' !important';
					}
					if ( empty( $decls ) ) {
						continue;
					}
					// The desktop column only becomes a flex column when an
					// alignment exists at desktop width — reintroduce it here
					// when a narrower device is the first to add alignment.
					if ( $flex ) {
						array_unshift( $decls, 'display:flex !important', 'flex-direction:column !important' );
					}
					// Suffix binds to every selector variant (see helper).
					$selector = self::responsive_selector_patterns( $entry['colStyles']['selector'], ':nth-child(' . ( $idx + 1 ) . ')' );
					$rules[ $selector ] = $decls;
				}
			}
			$selectors = isset( $entry['selectors'] ) ? $entry['selectors'] : array();
			foreach ( $selectors as $sel ) {
					$decls = array();
					if ( ! empty( $entry['props'] ) ) {
						foreach ( $entry['props'] as $key => $def ) {
							$variant = $device . '_' . $key;
							if ( ! isset( $settings[ $variant ] ) ) {
								continue;
							}
							$value = self::responsive_value_of( $def['type'], $settings[ $variant ] );
							if ( '' === $value ) {
								continue;
							}
							$prop = $def['prop'];
							if ( 'padding' === $prop && isset( $def['axis'] ) ) {
								// Inline banner button styles use the shorthand
								// `padding: y x`, so override the two longhands.
								$axis = 'x' === $def['axis'] ? array( 'padding-left', 'padding-right' ) : array( 'padding-top', 'padding-bottom' );
								foreach ( $axis as $ax_prop ) {
									$decls[] = $ax_prop . ':' . $value . ' !important';
								}
								continue;
							}
							$decls[] = $prop . ':' . $value . ' !important';
						}
					}
					if ( ! empty( $entry['vars'] ) ) {
						foreach ( $entry['vars'] as $key => $def ) {
							$variant = $device . '_' . $key;
							if ( ! isset( $settings[ $variant ] ) ) {
								continue;
							}
							$value = self::responsive_value_of( $def['type'], $settings[ $variant ] );
							if ( '' !== $value ) {
								$decls[] = $def['var'] . ':' . $value . ' !important';
							}
						}
					}
					if ( empty( $decls ) ) {
						continue;
					}
					$rules[ self::responsive_selector_patterns( $sel ) ] = $decls;
				}
			}

			// Inner-element CSS transform groups: entries declare their own
			// key prefix + selectors (e.g. title_ on .xsb-banner-title) and
			// emit one rule per device when that device's transform_type is
			// custom. Mirrors transform_css_props() desktop output.
			foreach ( $entries as $entry ) {
				if ( empty( $entry['transform'] ) ) {
					continue;
				}
				$t = $entry['transform'];
				$tprefix = isset( $t['prefix'] ) ? (string) $t['prefix'] : '';
				$tselectors = isset( $t['selectors'] ) && is_array( $t['selectors'] ) ? $t['selectors'] : array();
				if ( empty( $tselectors ) ) {
					continue;
				}
				$tdecls = self::transform_css_decls( $settings, $device, $tprefix );
				if ( empty( $tdecls ) ) {
					continue;
				}
				$tdecls_imp = array();
				foreach ( $tdecls as $td ) {
					$tdecls_imp[] = $td . ' !important';
				}
				foreach ( $tselectors as $tsel ) {
					$rules[ self::responsive_selector_patterns( $tsel ) ] = $tdecls_imp;
				}
			}

			if ( ! empty( $rules ) ) {
				$devices[ $device ] = $rules;
			}
		}

		// Position layer (generic, any block): desktop preset + per-device
		// presets/offsets become token-scoped rules (no media wrapper for the
		// desktop value, real @media for tablet/mobile — see the builder
		// helpers below).
		$position = self::position_device_map( $settings );
		foreach ( array( 'tablet', 'mobile' ) as $device ) {
			if ( empty( $position[ $device ] ) ) {
				continue;
			}
			if ( ! isset( $devices[ $device ] ) ) {
				$devices[ $device ] = array();
			}
			$token_sel = '[data-xsb-r="{TOKEN}"]';
			if ( ! isset( $devices[ $device ][ $token_sel ] ) ) {
				$devices[ $device ][ $token_sel ] = array();
			}
			foreach ( $position[ $device ] as $decl ) {
				$devices[ $device ][ $token_sel ][] = $decl . ' !important';
			}
		}

		if ( empty( $devices ) && empty( $position['desktop'] ) ) {
			return $html;
		}

		// Give the block root a stable per-instance token to scope the rules.
		$token  = $type . '-' . substr( md5( wp_json_encode( $settings ) ), 0, 8 );
		$tagged = self::tag_responsive_token( $html, $token );
		if ( false === $tagged ) {
			// First tag is not a plain element — cannot scope safely, skip.
			return $html;
		}
		$html = $tagged;

		$widths = array( 'tablet' => 768, 'mobile' => 480 );
		$css    = '';

		// Desktop position rule (applies at every width, like the inline
		// styles the renderers print — !important only where it must win
		// over a widget's own inline positioning).
		if ( ! empty( $position['desktop'] ) ) {
			$decls = array();
			foreach ( $position['desktop'] as $decl ) {
				$decls[] = $decl . ' !important';
			}
			// Absolute/fixed position nudges and the CSS transform both write
			// transform — emit the (composed) transform after the position
			// decls in the same rule so it wins the cascade and nothing is
			// silently dropped.
			foreach ( self::transform_css_decls( $settings, '', '' ) as $td ) {
				$decls[] = $td . ' !important';
			}
			$css .= "\n" . '[data-xsb-r="' . esc_attr( $token ) . '"] { ' . implode( '; ', $decls ) . '; }';
		}

		foreach ( $devices as $device => $rules ) {
			$media = '';
			foreach ( $rules as $selector => $decls ) {
				$selector = str_replace( '{TOKEN}', esc_attr( $token ), $selector );
				$media   .= "\n\t" . $selector . ' { ' . implode( '; ', $decls ) . '; }';
			}
			$css .= "\n@media (max-width: " . $widths[ $device ] . "px) {" . $media . "\n}";
		}

		// Deduplicate identical rule sets for repeated blocks (product cards).
		static $printed = array();
		if ( in_array( $token, $printed, true ) ) {
			return $html;
		}
		$printed[] = $token;

		self::enqueue_dynamic_css( $css );

		return $html;
	}

	/**
	 * Position keys (shared by every block type). 'position' chooses the
	 * CSS position model (in-flow / relative / absolute / fixed), the X/Y
	 * offsets nudge the widget from that anchor, and 'pos_z' is the stack
	 * order. Tablet/mobile behaviour is expressed through the responsive
	 * variant keys (tablet_position, tablet_pos_x, …).
	 *
	 * @return array
	 */
	private static function position_keys() {
		return array( 'position', 'pos_x', 'pos_y', 'pos_z' );
	}

	/**
	 * Position preset vocabulary. An empty value means "In flow / default"
	 * (the element keeps its normal layout position). Every other value is a
	 * CSS position declaration the emitter uses verbatim on the element.
	 *
	 * @return array list of preset values (labels live in config.js).
	 */
	private static function position_presets() {
		return array( '', 'relative', 'absolute', 'fixed' );
	}

	/**
	 * Desktop/tablet/mobile position rule map for one block.
	 *
	 * A device only emits when the effective 'position' on that device is
	 * non-empty. An empty 'position' means in-flow, so no rule is needed.
	 * Offsets are only meaningful on top of a non-default position.
	 * Tablet/mobile inherit the wider device's effective keys and only
	 * replace the ones whose tablet_/mobile_ variant is present.
	 *
	 * @param array $settings Raw settings.
	 * @return array device => decl list ('' when nothing to emit).
	 */
	private static function position_device_map( $settings ) {
		$map = array(
			'desktop' => array(),
			'tablet'  => array(),
			'mobile'  => array(),
		);

		if ( ! empty( $settings['position'] ) ) {
			$map['desktop'] = self::position_decls( $settings );
		}

		$effective = array( 'position' => isset( $settings['position'] ) ? (string) $settings['position'] : '' );
		foreach ( array( 'tablet', 'mobile' ) as $device ) {
			$has_variant = false;
			foreach ( self::position_keys() as $key ) {
				$variant = $device . '_' . $key;
				if ( array_key_exists( $variant, $settings ) ) {
					$effective[ $key ] = $settings[ $variant ];
					$has_variant       = true;
				}
			}
			if ( $has_variant && ! empty( $effective['position'] ) ) {
				$map[ $device ] = self::position_decls( $effective );
			}
		}

		return $map;
	}

	/**
	 * CSS declarations for one effective position layer. Emits only the
	 * 'position' value plus any offset/stack-order overrides.
	 *
	 * @param array $layer Effective settings for one device.
	 * @return array 'prop:value' declaration strings.
	 */
	private static function position_decls( $layer ) {
		$position = isset( $layer['position'] ) ? (string) $layer['position'] : '';
		$allowed  = self::position_presets();

		if ( '' !== $position && ! in_array( $position, $allowed, true ) ) {
			return array();
		}

		if ( '' === $position ) {
			return array();
		}

		$nudge = function ( $value ) {
			if ( ! isset( $value ) || '' === $value || ! is_numeric( $value ) ) {
				return 0;
			}
			return min( 800, max( -800, (float) $value ) );
		};
		$x = $nudge( isset( $layer['pos_x'] ) ? $layer['pos_x'] : 0 );
		$y = $nudge( isset( $layer['pos_y'] ) ? $layer['pos_y'] : 0 );
		$z = isset( $layer['pos_z'] ) && '' !== $layer['pos_z'] ? min( 999, max( 0, absint( $layer['pos_z'] ) ) ) : 0;

		$px = function ( $n ) {
			$n = (float) $n;
			if ( $n === (float) (int) $n ) {
				return (string) (int) $n . 'px';
			}
			return rtrim( rtrim( number_format( $n, 2, '.', '' ), '0' ), '.' ) . 'px';
		};

		$decls = array( 'position:' . $position );

		if ( 'relative' === $position ) {
			if ( 0 !== $x ) {
				$decls[] = 'left:' . $px( $x );
			}
			if ( 0 !== $y ) {
				$decls[] = 'top:' . $px( $y );
			}
		} elseif ( 'absolute' === $position ) {
			$decls[] = 'top:0';
			$decls[] = 'left:0';
			$decls[] = 'right:auto';
			$decls[] = 'bottom:auto';
			if ( 0 !== $x || 0 !== $y ) {
				$decls[] = 'transform:' . 'translate(' . $px( $x ) . ', ' . $px( $y ) . ')';
			}
		} elseif ( 'fixed' === $position ) {
			$decls[] = 'top:0';
			$decls[] = 'left:0';
			$decls[] = 'right:auto';
			$decls[] = 'bottom:auto';
			if ( 0 !== $x || 0 !== $y ) {
				$decls[] = 'transform:' . 'translate(' . $px( $x ) . ', ' . $px( $y ) . ')';
			}
		}

		if ( $z > 0 ) {
			$decls[] = 'z-index:' . (string) $z;
		}

		return $decls;
	}

	/**
	 * CSS transform props from the shared transform settings group
	 * (transform_type / transform_tx / transform_ty / transform_scale /
	 * transform_rotate / transform_origin). Works for any key prefix and any
	 * device layer, so the same helper feeds the block root (unprefixed,
	 * desktop + media), the prefixed inner elements (title_, item_, …) and
	 * the editor preview mirror.
	 *
	 * @param array  $settings Block settings.
	 * @param string $device   Device layer: '' = desktop/base, 'tablet', 'mobile'.
	 * @param string $prefix   Key prefix ('' for the block root, 'title'…).
	 * @return array CSS property => value (empty when transform is not custom).
	 */
	public static function transform_css_props( $settings, $device = '', $prefix = '' ) {
		$props = array();
		if ( ! is_array( $settings ) ) {
			return $props;
		}
		$d = '' !== $device ? $device . '_' : '';
		$p = '' !== $prefix ? $prefix . '_' : '';
		$base = $d . $p . 'transform_';

		if ( ! isset( $settings[ $base . 'type' ] ) || 'custom' !== $settings[ $base . 'type' ] ) {
			return $props;
		}

		$parts = array();
		$tx = isset( $settings[ $base . 'tx' ] ) ? (float) $settings[ $base . 'tx' ] : 0;
		$ty = isset( $settings[ $base . 'ty' ] ) ? (float) $settings[ $base . 'ty' ] : 0;
		if ( 0 !== $tx || 0 !== $ty ) {
			$parts[] = 'translate(' . self::format_px( $tx ) . 'px, ' . self::format_px( $ty ) . 'px)';
		}
		$scale = isset( $settings[ $base . 'scale' ] ) ? (float) $settings[ $base . 'scale' ] : 0;
		if ( $scale > 0 && 100 !== $scale ) {
			$parts[] = 'scale(' . rtrim( rtrim( number_format( $scale / 100, 4, '.', '' ), '0' ), '.' ) . ')';
		}
		$rotate = isset( $settings[ $base . 'rotate' ] ) ? (float) $settings[ $base . 'rotate' ] : 0;
		if ( 0 !== $rotate ) {
			$parts[] = 'rotate(' . rtrim( rtrim( number_format( $rotate, 2, '.', '' ), '0' ), '.' ) . 'deg)';
		}
		if ( ! empty( $parts ) ) {
			$props['transform'] = implode( ' ', $parts );
		}

		$origin = isset( $settings[ $base . 'origin' ] ) ? trim( (string) $settings[ $base . 'origin' ] ) : '';
		if ( '' !== $origin ) {
			$props['transform-origin'] = $origin;
		}

		return $props;
	}

	/**
	 * transform_css_props() flattened into ready-to-print declarations
	 * ('transform:…', 'transform-origin:…'). For the block root, an
	 * absolute/fixed position nudge also uses a translate transform, so the
	 * two features are composed into one transform string per device
	 * (prefixed inner elements never carry position keys and pass through
	 * unchanged).
	 *
	 * @param array  $settings Block settings.
	 * @param string $device   Device layer ('' = desktop).
	 * @param string $prefix   Key prefix.
	 * @return array
	 */
	public static function transform_css_decls( $settings, $device = '', $prefix = '' ) {
		$props = self::transform_css_props( $settings, $device, $prefix );
		if ( empty( $props ) ) {
			return array();
		}

		if ( '' === $prefix && isset( $props['transform'] ) ) {
			// Effective position for this device (desktop unless the device
			// overrides it), matching position_device_map's cascade.
			$position = isset( $settings['position'] ) ? $settings['position'] : '';
			$pos_x    = isset( $settings['pos_x'] ) ? (float) $settings['pos_x'] : 0;
			$pos_y    = isset( $settings['pos_y'] ) ? (float) $settings['pos_y'] : 0;
			if ( '' !== $device ) {
				if ( isset( $settings[ $device . '_position' ] ) ) {
					$position = $settings[ $device . '_position' ];
				}
				if ( isset( $settings[ $device . '_pos_x' ] ) ) {
					$pos_x = (float) $settings[ $device . '_pos_x' ];
				}
				if ( isset( $settings[ $device . '_pos_y' ] ) ) {
					$pos_y = (float) $settings[ $device . '_pos_y' ];
				}
			}
			if ( in_array( $position, array( 'absolute', 'fixed' ), true ) && ( 0 !== $pos_x || 0 !== $pos_y ) ) {
				$props['transform'] = 'translate(' . self::format_px( $pos_x ) . 'px, ' . self::format_px( $pos_y ) . 'px) ' . $props['transform'];
			}
		}

		$decls = array();
		foreach ( $props as $prop => $value ) {
			$decls[] = $prop . ':' . $value;
		}
		return $decls;
	}

	/**
	 * Format a px value as a compact CSS number (0 stays '0', fractions keep
	 * up to two decimals).
	 *
	 * @param float $n Value.
	 * @return string
	 */
	private static function format_px( $n ) {
		$n = (float) $n;
		if ( $n === (float) (int) $n ) {
			return (string) (int) $n;
		}
		return rtrim( rtrim( number_format( $n, 2, '.', '' ), '0' ), '.' );
	}

	/**
	 * Apply the desktop CSS transform to the block root element (injected
	 * into its style attribute). Works for every block: the transform group
	 * rides the flat unprefixed settings keys, so any widget whose popover
	 * exposes the Transform category on a root element gets the effect here
	 * without per-widget code. Prefixed inner-element transforms are handled
	 * by the per-element style builders (heading_style_attr, chrome_css_props).
	 *
	 * @param string $html     Rendered block HTML.
	 * @param array  $settings Block settings.
	 * @return string
	 */
	public static function apply_transform_root( $html, $settings ) {
		$decls = self::transform_css_decls( $settings, '', '' );
		if ( empty( $decls ) || '' === $html ) {
			return $html;
		}

		$pos = strpos( $html, '<' );
		if ( false === $pos ) {
			return $html;
		}
		$end = strpos( $html, '>', $pos );
		if ( false === $end ) {
			return $html;
		}
		$tag = substr( $html, $pos, $end - $pos + 1 );
		if ( ! preg_match( '/^<[a-zA-Z][a-zA-Z0-9]*([\s>])/', $tag ) ) {
			return $html;
		}

		$addition = implode( '; ', $decls );
		if ( preg_match( '/\sstyle="([^"]*)"/i', $tag, $m ) ) {
			$new_tag = str_replace( $m[0], ' style="' . $m[1] . ( '' !== $m[1] ? '; ' : '' ) . $addition . '"', $tag );
		} elseif ( preg_match( '/\sstyle=\'([^\']*)\'/i', $tag, $m ) ) {
			$new_tag = str_replace( $m[0], " style='" . $m[1] . ( '' !== $m[1] ? '; ' : '' ) . $addition . "'", $tag );
		} elseif ( substr( $tag, - 1 ) === '>' ) {
			$new_tag = substr( $tag, 0, - 1 ) . ' style="' . $addition . '">';
		} elseif ( preg_match( '/\s\/>$/', $tag ) ) {
			$new_tag = preg_replace( '/\s\/>$/', ' style="' . $addition . '" />', $tag );
		} else {
			return $html;
		}

		return substr_replace( $html, $new_tag, $pos, strlen( $tag ) );
	}

	/**
	 * Selector variants for one inner element: the element may be the token
	 * holder itself, a descendant of it, or a following sibling (when an
	 * optional element such as the ordering title precedes the wrapper).
	 *
	 * @param string $sel    Element selector ('' = token element itself).
	 * @param string $suffix Optional suffix appended to every variant (e.g.
	 *                       ':nth-child(2)') — never append it after the
	 *                       joined list, that would only bind the last one.
	 * @return string CSS selector with {TOKEN} placeholder.
	 */
	private static function responsive_selector_patterns( $sel, $suffix = '' ) {
		$token = '[data-xsb-r="{TOKEN}"]';
		if ( '' === $sel ) {
			return $token . $suffix;
		}
		$parts = array(
			$token . ' ' . $sel,
			$token . $sel,
			$token . ' ~ ' . $sel,
		);
		if ( '' !== $suffix ) {
			foreach ( $parts as &$part ) {
				$part .= $suffix;
			}
		}
		return implode( ', ', $parts );
	}

	/**
	 * Banner background declarations, shared by the renderer (inline styles)
	 * and the responsive emitter (per-device @media) so a tablet/mobile
	 * override composes exactly like the desktop background. Returns plain
	 * 'property:value' strings (values are sanitised before they get here).
	 *
	 * @param array $settings Effective banner settings for one device.
	 * @return array
	 */
	public static function banner_bg_decls( $settings ) {
		$val = function ( $key, $default ) use ( $settings ) {
			return isset( $settings[ $key ] ) && '' !== $settings[ $key ] ? $settings[ $key ] : $default;
		};

		$bg_type        = $val( 'bg_type', 'color' );
		$bg_color       = $val( 'bg_color', '#2563eb' );
		$gradient_type  = $val( 'gradient_type', 'linear' );
		$gradient_angle = (float) $val( 'gradient_angle', 180 );
		$gradient_shape = $val( 'gradient_radial_shape', 'circle' );
		$gradient_pos   = $val( 'gradient_position', 'center' );
		$gradient_a     = $val( 'gradient_color_a', '#2563eb' );
		$gradient_b     = $val( 'gradient_color_b', '#4f46e5' );
		$bg_image       = $val( 'bg_image', '' );
		$bg_size        = $val( 'bg_size', 'cover' );
		$bg_position    = $val( 'bg_position', 'center center' );
		$bg_repeat      = $val( 'bg_repeat', 'no-repeat' );
		$bg_attachment  = $val( 'bg_attachment', 'scroll' );

		$decls = array();

		if ( 'gradient' === $bg_type ) {
			$shapes = array( 'circle', 'ellipse' );
			$positions = array( 'center', 'top', 'bottom', 'left', 'right', 'top left', 'top right', 'bottom left', 'bottom right' );
			if ( ! in_array( $gradient_shape, $shapes, true ) ) {
				$gradient_shape = 'circle';
			}
			if ( ! in_array( $gradient_pos, $positions, true ) ) {
				$gradient_pos = 'center';
			}
			$decls[] = 'background-color:' . $bg_color;
			if ( 'radial' === $gradient_type ) {
				$decls[] = 'background-image:radial-gradient(' . $gradient_shape . ' at ' . $gradient_pos . ', ' . $gradient_a . ', ' . $gradient_b . ')';
			} else {
				$angle = min( 360, max( 0, $gradient_angle ) );
				$decls[] = 'background-image:linear-gradient(' . $angle . 'deg, ' . $gradient_a . ', ' . $gradient_b . ')';
			}
		} elseif ( 'image' === $bg_type && $bg_image ) {
			$decls[] = 'background-image:url(' . $bg_image . ')';
			$decls[] = 'background-size:' . $bg_size;
			$decls[] = 'background-position:' . $bg_position;
			$decls[] = 'background-repeat:' . $bg_repeat;
			$decls[] = 'background-attachment:' . $bg_attachment;
			$decls[] = 'background-color:' . $bg_color;
		} else {
			$decls[] = 'background-color:' . $bg_color;
		}

		return $decls;
	}

	/**
	 * True when a device layer holds any banner background/overlay/placement
	 * override (used to decide whether per-device banner rules are needed).
	 *
	 * @param array  $settings Raw settings.
	 * @param string $device   Device.
	 * @return bool
	 */
	private static function banner_device_has_variants( $settings, $device ) {
		$keys = array_merge( self::banner_bg_keys(), array( 'min_height', 'content_position_x', 'content_position_y' ) );
		foreach ( $keys as $key ) {
			if ( isset( $settings[ $device . '_' . $key ] ) ) {
				return true;
			}
		}
		return false;
	}

	/**
	 * Banner background-family keys (color/gradient/image/video/overlay).
	 *
	 * @return array
	 */
	private static function banner_bg_keys() {
		return array( 'bg_type', 'bg_color', 'gradient_type', 'gradient_angle', 'gradient_radial_shape', 'gradient_position', 'gradient_color_a', 'gradient_color_b', 'bg_image', 'bg_size', 'bg_position', 'bg_repeat', 'bg_attachment', 'bg_video', 'overlay_color', 'overlay_opacity' );
	}

	/**
	 * Banner settings with the device layer(s) merged onto the base keys so
	 * the shared background builder can compose the device's background.
	 * Mobile inherits tablet (mirroring the JS layer + CSS cascade).
	 *
	 * @param array  $settings Raw settings.
	 * @param string $device   Device.
	 * @return array
	 */
	private static function banner_layer_for_device( $settings, $device ) {
		$layer  = $settings;
		$device_keys = array_merge( self::banner_bg_keys(), array( 'min_height', 'content_position_x', 'content_position_y' ) );
		$layers = 'mobile' === $device ? array( 'tablet', 'mobile' ) : array( $device );
		foreach ( $layers as $dev ) {
			foreach ( $device_keys as $key ) {
				if ( isset( $settings[ $dev . '_' . $key ] ) ) {
					$layer[ $key ] = $settings[ $dev . '_' . $key ];
				}
			}
		}
		return $layer;
	}

	/**
	 * Add per-device banner rules (background + overlay + flex placement) to
	 * the rules map for one device. Scoped to the banner token; the overlay
	 * targets its child so media/background changes cascade correctly.
	 *
	 * @param array  $rules    Rules map (selector => decl list).
	 * @param string $device   Device.
	 * @param array  $settings Raw settings.
	 */
	private static function banner_responsive_rules( &$rules, $device, $settings ) {
		if ( ! self::banner_device_has_variants( $settings, $device ) ) {
			return;
		}

		$layer = self::banner_layer_for_device( $settings, $device );
		$bg_keys = self::banner_bg_keys();
		$has_bg  = false;
		$has_pos = false;
		foreach ( $bg_keys as $key ) {
			if ( isset( $settings[ $device . '_' . $key ] ) ) {
				$has_bg = true;
				break;
			}
		}
		foreach ( array( 'content_position_x', 'content_position_y' ) as $key ) {
			if ( isset( $settings[ $device . '_' . $key ] ) ) {
				$has_pos = true;
				break;
			}
		}

		$decls = array();

		// Background family (color/gradient/image/video/overlay).
		if ( $has_bg ) {
			$decls = self::banner_bg_decls( $layer );
		}

		// The renderer sizes the banner with `height`, not min-height.
		if ( isset( $settings[ $device . '_min_height' ] ) ) {
			$decls[] = 'height:' . absint( $layer['min_height'] ) . 'px';
		}

		// Flex placement of the content (mirrors the renderer's
		// left/center/right + top/center/bottom maps) — only when changed.
		if ( $has_pos ) {
			$flex_x = array( 'left' => 'flex-start', 'center' => 'center', 'right' => 'flex-end' );
			$flex_y = array( 'top' => 'flex-start', 'center' => 'center', 'bottom' => 'flex-end' );
			$pos_x  = isset( $layer['content_position_x'] ) ? $layer['content_position_x'] : 'center';
			$pos_y  = isset( $layer['content_position_y'] ) ? $layer['content_position_y'] : 'center';
			if ( isset( $flex_x[ $pos_x ] ) ) {
				$decls[] = 'align-items:' . $flex_x[ $pos_x ];
			}
			if ( isset( $flex_y[ $pos_y ] ) ) {
				$decls[] = 'justify-content:' . $flex_y[ $pos_y ];
			}
		}

		$token = '[data-xsb-r="{TOKEN}"]';
		if ( ! isset( $rules[ $token ] ) ) {
			$rules[ $token ] = array();
		}
		foreach ( $decls as $decl ) {
			$rules[ $token ][] = $decl . ' !important';
		}

		// Overlay layer (only rendered by the renderer over image/video).
		if ( $has_bg ) {
			$bg_type = isset( $layer['bg_type'] ) ? $layer['bg_type'] : 'color';
			$overlay_color = isset( $layer['overlay_color'] ) && '' !== $layer['overlay_color'] ? $layer['overlay_color'] : '';
			$sel = self::responsive_selector_patterns( '.xsb-banner-overlay' );

			if ( in_array( $bg_type, array( 'image', 'video' ), true ) && '' !== $overlay_color ) {
				$opacity = isset( $layer['overlay_opacity'] ) ? min( 100, max( 0, absint( $layer['overlay_opacity'] ) ) ) : 45;
				if ( ! isset( $rules[ $sel ] ) ) {
					$rules[ $sel ] = array();
				}
				$rules[ $sel ][] = 'background-color:' . $overlay_color . ' !important';
				$rules[ $sel ][] = 'opacity:' . sprintf( '%.2f', $opacity / 100 ) . ' !important';
			} elseif ( in_array( $bg_type, array( 'image', 'video' ), true ) ) {
				// Media background but overlay turned off on this device: hide any
				// overlay element the desktop renderer may have emitted.
				$rules[ $sel ] = array( 'background-color:transparent !important', 'opacity:0 !important' );
			}
		}
	}

	/**
	 * Value helper for the inner map (mirrors responsive_css_value).
	 *
	 * @param string $type  'px' | 'raw' | 'float' | 'shadow' | 'cols'.
	 * @param mixed  $value Stored value.
	 * @return string
	 */
	private static function responsive_value_of( $type, $value ) {
		if ( 'px' === $type ) {
			$n = absint( $value );
			return $n > 0 ? $n . 'px' : '';
		}
		if ( 'float' === $type ) {
			$n = (float) $value;
			return $n > 0 ? (string) $n : '';
		}
		if ( 'shadow' === $type ) {
			return self::shadow_css( (string) $value );
		}
		if ( 'cols' === $type ) {
			// Grid reflow: N equal tracks (matches the desktop inline
			// grid-template-columns:repeat(N, minmax(0,1fr))).
			$n = min( 6, max( 1, absint( $value ) ) );
			return 'repeat(' . $n . ', minmax(0,1fr))';
		}
		$clean = trim( (string) $value );
		return '' === $clean ? '' : $clean;
	}

	/**
	 * Cart / checkout box placement: per-device align (left/center/right)
	 * means auto margins around the box, and a per-device max-width also
	 * forces width:100% so the narrower box actually centers.
	 *
	 * @param array  $rules    Rules map.
	 * @param string $device   Device.
	 * @param array  $settings Raw settings.
	 */
	private static function cc_placement_rules( &$rules, $device, $settings ) {
		$token  = '[data-xsb-r="{TOKEN}"]';
		$decls  = array();
		$align  = isset( $settings[ $device . '_align' ] ) ? $settings[ $device . '_align' ] : '';

		if ( 'center' === $align ) {
			$decls[] = 'margin-left:auto';
			$decls[] = 'margin-right:auto';
		} elseif ( 'right' === $align ) {
			$decls[] = 'margin-left:auto';
			$decls[] = 'margin-right:0';
		} elseif ( 'left' === $align ) {
			$decls[] = 'margin-left:0';
			$decls[] = 'margin-right:0';
		}

		if ( ! empty( $settings[ $device . '_max_width' ] ) ) {
			$decls[] = 'width:100%';
		}

		if ( ! empty( $decls ) ) {
			if ( ! isset( $rules[ $token ] ) ) {
				$rules[ $token ] = array();
			}
			foreach ( $decls as $decl ) {
				$rules[ $token ][] = $decl . ' !important';
			}
		}
	}

