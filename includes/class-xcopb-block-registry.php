	/**
	 * Build an inline `style` attribute from css-prop => value pairs. Empty
	 * and undefined values are skipped.
	 *
	 * @param array $props Associative css property → value.
	 * @return string ' style="…"' or '' when nothing to output.
	 */
	public static function inline_style_attr( $props ) {
		$css = '';
		foreach ( $props as $prop => $value ) {
			if ( '' === $value || null === $value ) {
				continue;
			}
			$css .= $prop . ':' . $value . ';';
		}
		return $css ? ' style="' . esc_attr( $css ) . '"' : '';
	}

	/**
	 * Typography + margin css props from the shared text settings.
	 *
	 * @param array $settings        Block settings.
	 * @param bool  $allow_transform Include text-transform.
	 * @return array
	 */
	public static function text_css_props( $settings, $allow_transform = false ) {
		$props = array();

		if ( ! empty( $settings['color'] ) ) {
			$props['color'] = $settings['color'];
		}
		if ( ! empty( $settings['align'] ) ) {
			$props['text-align'] = $settings['align'];
		}
		if ( ! empty( $settings['font_family'] ) ) {
			$props['font-family'] = $settings['font_family'];
		}
		if ( isset( $settings['font_size'] ) && '' !== $settings['font_size'] ) {
			$props['font-size'] = absint( $settings['font_size'] ) . 'px';
		}
		if ( ! empty( $settings['font_weight'] ) ) {
			$props['font-weight'] = $settings['font_weight'];
		}
		if ( isset( $settings['line_height'] ) && '' !== $settings['line_height'] ) {
			$props['line-height'] = (float) $settings['line_height'];
		}
		if ( isset( $settings['letter_spacing'] ) && '' !== $settings['letter_spacing'] ) {
			$props['letter-spacing'] = (float) $settings['letter_spacing'] . 'px';
		}
		if ( $allow_transform && ! empty( $settings['text_transform'] ) && 'none' !== $settings['text_transform'] ) {
			$props['text-transform'] = $settings['text_transform'];
		}
		if ( ! empty( $settings['font_style'] ) ) {
			$props['font-style'] = $settings['font_style'];
		}
		if ( ! empty( $settings['text_decoration'] ) ) {
			$props['text-decoration'] = $settings['text_decoration'];
		}
		if ( ! empty( $settings['background'] ) ) {
			$props['background'] = $settings['background'];
		}
		if ( isset( $settings['max_width'] ) && '' !== $settings['max_width'] && (int) $settings['max_width'] > 0 ) {
			$props['max-width'] = absint( $settings['max_width'] ) . 'px';
			$props['width']     = '100%';
		}
		if ( isset( $settings['opacity'] ) && '' !== $settings['opacity'] ) {
			$props['opacity'] = sprintf( '%.2f', min( 100, max( 0, absint( $settings['opacity'] ) ) ) / 100 );
		}

		foreach ( array( 'top', 'right', 'bottom', 'left' ) as $side ) {
			$key = 'margin_' . $side;
			if ( isset( $settings[ $key ] ) && '' !== $settings[ $key ] ) {
				$props[ 'margin-' . $side ] = (float) $settings[ $key ] . 'px';
			}
		}

		foreach ( array( 'top', 'right', 'bottom', 'left' ) as $side ) {
			$key = 'padding_' . $side;
			if ( isset( $settings[ $key ] ) && '' !== $settings[ $key ] ) {
				$props[ 'padding-' . $side ] = (float) $settings[ $key ] . 'px';
			}
		}

		return $props;
	}

	/**
	 * Box chrome css props (background, border, radius, shadow) for keys
	 * prefixed with $prefix.
	 *
	 * @param array  $settings Block settings.
	 * @param string $prefix   e.g. 'item', 'card', 'img'.
	 * @return array
	 */
	public static function chrome_css_props( $settings, $prefix = '' ) {
		$props = array();

		$bg_key = $prefix ? $prefix . '_bg' : 'background';
		if ( ! empty( $settings[ $bg_key ] ) ) {
			$props['background'] = $settings[ $bg_key ];
		}

		// Read the underscore keys the editor writes (item_border_width…);
		// with no prefix the keys are plain (border_width, shadow…). Legacy
		// no-underscore keys (itemborder_width…) are still honoured.
		$read = function ( $key, $fallback = '' ) use ( $prefix, $settings ) {
			$new_key = $prefix ? $prefix . '_' . $key : $key;
			$old_key = $prefix . $key;

			if ( isset( $settings[ $new_key ] ) ) {
				return $settings[ $new_key ];
			}
			if ( $prefix && isset( $settings[ $old_key ] ) ) {
				return $settings[ $old_key ];
			}
			return $fallback;
		};

		$width = absint( $read( 'border_width' ) );
		if ( $width > 0 ) {
			$style = $read( 'border_style', 'solid' );
			$style = $style ? $style : 'solid';
			$color = $read( 'border_color' );
			$color = $color ? $color : '#000000';
			$props['border'] = $width . 'px ' . $style . ' ' . $color;
		}
		$radius = absint( $read( 'border_radius' ) );
		if ( $radius > 0 ) {
			$props['border-radius'] = $radius . 'px';
		}
		$shadow = self::shadow_css( $read( 'shadow', 'none' ) );
		if ( $shadow ) {
			$props['box-shadow'] = $shadow;
		}

		// CSS transform (prefixed keys, e.g. item_transform_type).
		$props = array_merge( $props, self::transform_css_props( $settings, '', $prefix ) );

		return $props;
	}

	/**
	 * Heading typography (prefixed keys, e.g. title_color …) as an inline
	 * style attribute — used for the optional term-block titles.
	 *
	 * @param array  $settings Block settings.
	 * @param string $prefix   Key prefix (e.g. 'title').
	 * @return string
	 */
	public static function heading_style_attr( $settings, $prefix = 'title' ) {
		$props = array();

		if ( ! empty( $settings[ $prefix . '_color' ] ) ) {
			$props['color'] = $settings[ $prefix . '_color' ];
		}
		if ( ! empty( $settings[ $prefix . '_font_family' ] ) ) {
			$props['font-family'] = $settings[ $prefix . '_font_family' ];
		}
		if ( isset( $settings[ $prefix . '_font_size' ] ) && '' !== $settings[ $prefix . '_font_size' ] ) {
			$props['font-size'] = absint( $settings[ $prefix . '_font_size' ] ) . 'px';
		}
		if ( ! empty( $settings[ $prefix . '_font_weight' ] ) ) {
			$props['font-weight'] = $settings[ $prefix . '_font_weight' ];
		}
		if ( isset( $settings[ $prefix . '_line_height' ] ) && '' !== $settings[ $prefix . '_line_height' ] ) {
			$props['line-height'] = (float) $settings[ $prefix . '_line_height' ];
		}
		if ( isset( $settings[ $prefix . '_letter_spacing' ] ) && '' !== $settings[ $prefix . '_letter_spacing' ] ) {
			$props['letter-spacing'] = (float) $settings[ $prefix . '_letter_spacing' ] . 'px';
		}
		if ( ! empty( $settings[ $prefix . '_text_transform' ] ) && 'none' !== $settings[ $prefix . '_text_transform' ] ) {
			$props['text-transform'] = $settings[ $prefix . '_text_transform' ];
		}
		if ( ! empty( $settings[ $prefix . '_font_style' ] ) ) {
			$props['font-style'] = $settings[ $prefix . '_font_style' ];
		}
		if ( ! empty( $settings[ $prefix . '_text_decoration' ] ) ) {
			$props['text-decoration'] = $settings[ $prefix . '_text_decoration' ];
		}
		if ( ! empty( $settings[ $prefix . '_margin_bottom' ] ) ) {
			$props['margin-bottom'] = absint( $settings[ $prefix . '_margin_bottom' ] ) . 'px';
		}

		// CSS transform (prefixed keys, e.g. title_transform_type).
		$props = array_merge( $props, self::transform_css_props( $settings, '', $prefix ) );

		return self::inline_style_attr( $props );
	}

	/**
	 * Button css custom properties (CSS vars) placed on a wrapper so the
	 * public stylesheet can style the theme/woocommerce button itself.
	 *
	 * @param array  $settings Block settings.
	 * @param string $prefix   Settings key prefix (e.g. 'button').
	 * @return array
	 */
	public static function button_vars( $settings, $prefix = 'button' ) {
		$vars = array();

		if ( ! empty( $settings[ $prefix . '_bg_color' ] ) ) {
			$vars['--xsb-btn-bg'] = $settings[ $prefix . '_bg_color' ];
		}
		if ( ! empty( $settings[ $prefix . '_text_color' ] ) ) {
			$vars['--xsb-btn-fg'] = $settings[ $prefix . '_text_color' ];
		}
		if ( ! empty( $settings[ $prefix . '_border_color' ] ) ) {
			$vars['--xsb-btn-bd'] = $settings[ $prefix . '_border_color' ];
		}
		foreach ( array( 'border_width' => '--xsb-btn-bdw', 'border_radius' => '--xsb-btn-r', 'padding_x' => '--xsb-btn-px', 'padding_y' => '--xsb-btn-py', 'font_size' => '--xsb-btn-fs' ) as $key => $var ) {
			if ( ! empty( $settings[ $prefix . '_' . $key ] ) ) {
				$vars[ $var ] = absint( $settings[ $prefix . '_' . $key ] ) . 'px';
			}
		}
		if ( ! empty( $settings[ $prefix . '_font_family' ] ) ) {
			$vars['--xsb-btn-ff'] = $settings[ $prefix . '_font_family' ];
		}
		if ( ! empty( $settings[ $prefix . '_font_weight' ] ) ) {
			$vars['--xsb-btn-fw'] = $settings[ $prefix . '_font_weight' ];
		}
		if ( ! empty( $settings[ $prefix . '_hover_bg' ] ) ) {
			$vars['--xsb-btn-hover-bg'] = $settings[ $prefix . '_hover_bg' ];
		}
		if ( ! empty( $settings[ $prefix . '_hover_color' ] ) ) {
			$vars['--xsb-btn-hover-fg'] = $settings[ $prefix . '_hover_color' ];
		}

		return $vars;
	}

	/**
	 * Hover color, hide-on-device and button hover CSS that cannot live inline.
	 *
	 * @param string $type     Block type.
	 * @param string $html     Rendered HTML.
	 * @param array  $settings Block settings.
	 * @return string
	 */
	public static function apply_interaction( $type, $html, $settings ) {
		if ( '' === $html || ! is_array( $settings ) ) {
			return $html;
		}

		$hover   = ! empty( $settings['hover_color'] ) ? $settings['hover_color'] : '';
		$hide_d  = ! empty( $settings['hide_on_desktop'] );
		$hide_t  = ! empty( $settings['hide_on_tablet'] );
		$hide_m  = ! empty( $settings['hide_on_mobile'] );
		$btn_hbg = ! empty( $settings['button_hover_bg'] ) ? $settings['button_hover_bg'] : '';
		$btn_hfg = ! empty( $settings['button_hover_color'] ) ? $settings['button_hover_color'] : '';
		$button_hover_bg = ! empty( $settings['hover_bg_color'] ) ? $settings['hover_bg_color'] : '';
		$button_hover_fg = ! empty( $settings['hover_text_color'] ) ? $settings['hover_text_color'] : '';
		$button_focus_bg = ! empty( $settings['focus_bg_color'] ) ? $settings['focus_bg_color'] : '';
		$button_focus_fg = ! empty( $settings['focus_text_color'] ) ? $settings['focus_text_color'] : '';
		$button_hover_border = ! empty( $settings['hover_border_color'] ) ? $settings['hover_border_color'] : '';
		$button_focus_border = ! empty( $settings['focus_border_color'] ) ? $settings['focus_border_color'] : '';
		$widget_hover_bg = ! empty( $settings['hover_bg_color'] ) ? $settings['hover_bg_color'] : '';
		$widget_hover_fg = ! empty( $settings['hover_text_color'] ) ? $settings['hover_text_color'] : '';
		$widget_focus_bg = ! empty( $settings['focus_bg_color'] ) ? $settings['focus_bg_color'] : '';
		$widget_focus_fg = ! empty( $settings['focus_text_color'] ) ? $settings['focus_text_color'] : '';
		$widget_hover_border = ! empty( $settings['hover_border_color'] ) ? $settings['hover_border_color'] : '';
		$widget_focus_border = ! empty( $settings['focus_border_color'] ) ? $settings['focus_border_color'] : '';

		if ( '' === $hover && ! $hide_d && ! $hide_t && ! $hide_m && '' === $btn_hbg && '' === $btn_hfg && '' === $button_hover_bg && '' === $button_hover_fg && '' === $button_focus_bg && '' === $button_focus_fg && '' === $button_hover_border && '' === $button_focus_border && '' === $widget_hover_bg && '' === $widget_hover_fg && '' === $widget_focus_bg && '' === $widget_focus_fg && '' === $widget_hover_border && '' === $widget_focus_border ) {
			return $html;
		}

		$token = '';
		if ( preg_match( '/data-xsb-r="([^"]+)"/', $html, $match ) ) {
			$token = $match[1];
		} else {
			$token  = $type . '-' . substr( md5( wp_json_encode( $settings ) . 'ix' ), 0, 8 );
			$tagged = self::tag_responsive_token( $html, $token );
			if ( false === $tagged ) {
				return $html;
			}
			$html = $tagged;
		}

		$sel = '[data-xsb-r="' . esc_attr( $token ) . '"]';
		$css = '';
		$widget_targets = array(
			'xcopb/gb-heading' => ' .xsb-heading',
			'xcopb/gb-button' => ' .xsb-button',
			'xcopb/gb-image' => ' img',
			'xcopb/gb-text' => '',
			'xcopb/gb-divider' => ' .xsb-divider',
			'xcopb/gb-container' => '',
		);
		$widget_target = isset( $widget_targets[ $type ] ) ? $sel . $widget_targets[ $type ] : '';
		if ( '' !== $widget_target && ( '' !== $widget_hover_bg || '' !== $widget_hover_fg || '' !== $widget_hover_border ) ) {
			$decls = array();
			if ( '' !== $widget_hover_bg ) { $decls[] = 'background:' . $widget_hover_bg . ' !important'; }
			if ( '' !== $widget_hover_fg ) { $decls[] = 'color:' . $widget_hover_fg . ' !important'; }
			if ( '' !== $widget_hover_border ) { $decls[] = 'border-color:' . $widget_hover_border . ' !important'; }
			$css .= $widget_target . ':hover{' . implode( ';', $decls ) . ';}';
		}
		if ( '' !== $widget_target && ( '' !== $widget_focus_bg || '' !== $widget_focus_fg || '' !== $widget_focus_border ) ) {
			$decls = array();
			if ( '' !== $widget_focus_bg ) { $decls[] = 'background:' . $widget_focus_bg . ' !important'; }
			if ( '' !== $widget_focus_fg ) { $decls[] = 'color:' . $widget_focus_fg . ' !important'; }
			if ( '' !== $widget_focus_border ) { $decls[] = 'border-color:' . $widget_focus_border . ' !important'; }
			$css .= $widget_target . ':focus-visible{' . implode( ';', $decls ) . ';outline:2px solid currentColor;outline-offset:2px;}';
		}
		if ( isset( $settings['hover_box_shadow'] ) && '' !== $widget_target ) {
			$hover_shadow = $settings['hover_box_shadow'];
			if ( is_string( $hover_shadow ) && isset( array( 'soft' => '0 4px 14px rgba(0,0,0,.12)', 'medium' => '0 10px 28px rgba(0,0,0,.18)', 'strong' => '0 18px 50px rgba(0,0,0,.28)' )[ $hover_shadow ] ) ) {
				$css .= $widget_target . ':hover{box-shadow:' . array( 'soft' => '0 4px 14px rgba(0,0,0,.12)', 'medium' => '0 10px 28px rgba(0,0,0,.18)', 'strong' => '0 18px 50px rgba(0,0,0,.28)' )[ $hover_shadow ] . ' !important;}';
			}
		}
		if ( '' !== $widget_target && '' !== $widget_focus_border ) {
			$css .= $widget_target . ':focus-visible{border-color:' . esc_attr( $widget_focus_border ) . ' !important;}';
		}
		$state_targets = array( 'xcopb/gb-heading' => '.xsb-heading', 'xcopb/gb-button' => '.xsb-button', 'xcopb/gb-image' => ' img', 'xcopb/gb-text' => '', 'xcopb/gb-divider' => ' .xsb-divider' );
		if ( isset( $state_targets[ $type ] ) ) {
			$state_selector = $sel . $state_targets[ $type ];
			$radius = isset( $settings['hover_border_radius'] ) ? max( 0, (float) $settings['hover_border_radius'] ) : null;
			if ( null !== $radius ) { $css .= $state_selector . ':hover{border-radius:' . $radius . 'px !important;}'; }
			$shadow_map = array( 'soft' => '0 4px 14px rgba(0,0,0,.12)', 'medium' => '0 10px 28px rgba(0,0,0,.18)', 'strong' => '0 18px 50px rgba(0,0,0,.28)' );
			if ( ! empty( $settings['hover_box_shadow'] ) && isset( $shadow_map[ $settings['hover_box_shadow'] ] ) ) { $css .= $state_selector . ':hover{box-shadow:' . $shadow_map[ $settings['hover_box_shadow'] ] . ' !important;}'; }
			if ( isset( $settings['hover_opacity'] ) ) { $css .= $state_selector . ':hover{opacity:' . ( min( 100, max( 0, (float) $settings['hover_opacity'] ) ) / 100 ) . ' !important;}'; }
			if ( 'xcopb/gb-image' === $type && isset( $settings['hover_grayscale'] ) ) { $css .= $state_selector . ':hover{filter:grayscale(' . min( 100, max( 0, (float) $settings['hover_grayscale'] ) ) . '%) !important;}'; }
			if ( 'xcopb/gb-image' === $type && isset( $settings['grayscale'] ) ) { $css .= $state_selector . '{filter:grayscale(' . min( 100, max( 0, (float) $settings['grayscale'] ) ) . '%);}'; }
		}

		if ( '' !== $hover ) {
			$css .= $sel . ':hover,' . $sel . ':hover a{color:' . $hover . ' !important;}';
		}
		if ( $hide_d ) {
			$css .= '@media (min-width:769px){' . $sel . '{display:none !important;}}';
		}
		if ( $hide_t ) {
			$css .= '@media (max-width:768px) and (min-width:481px){' . $sel . '{display:none !important;}}';
		}
		if ( $hide_m ) {
			$css .= '@media (max-width:480px){' . $sel . '{display:none !important;}}';
		}
		if ( '' !== $btn_hbg || '' !== $btn_hfg || '' !== $button_hover_bg || '' !== $button_hover_fg || '' !== $button_hover_border ) {
			$btn_sel = $sel . ' .button:hover,' . $sel . ' button:hover,' . $sel . ' .single_add_to_cart_button:hover,' . $sel . ' .xsb-woo-search-button:hover';
			$decls   = array();
			$hover_bg_value = '' !== $button_hover_bg ? $button_hover_bg : $btn_hbg;
			$hover_fg_value = '' !== $button_hover_fg ? $button_hover_fg : $btn_hfg;
			if ( '' !== $hover_bg_value ) {
				$decls[] = 'background-color:' . $hover_bg_value . ' !important';
			}
			if ( '' !== $hover_fg_value ) {
				$decls[] = 'color:' . $hover_fg_value . ' !important';
			}
			if ( '' !== $button_hover_border ) { $decls[] = 'border-color:' . $button_hover_border . ' !important'; }
			if ( 'xcopb/gb-button' === $type ) { $css .= $widget_target . ':hover{' . implode( ';', $decls ) . ';}'; }
			else { $css .= $btn_sel . '{' . implode( ';', $decls ) . ';}'; }
		}
		if ( '' !== $button_focus_bg || '' !== $button_focus_fg || '' !== $button_focus_border ) {
			$decls = array();
			if ( '' !== $button_focus_bg ) { $decls[] = 'background-color:' . $button_focus_bg . ' !important'; }
			if ( '' !== $button_focus_fg ) { $decls[] = 'color:' . $button_focus_fg . ' !important'; }
			if ( '' !== $button_focus_border ) { $decls[] = 'border-color:' . $button_focus_border . ' !important'; }
			if ( 'xcopb/gb-button' === $type ) { $css .= $widget_target . ':focus-visible{' . implode( ';', $decls ) . ';outline:2px solid currentColor;outline-offset:2px;}'; }
			else { $css .= $sel . ' a:focus-visible,' . $sel . ' button:focus-visible,' . $sel . ' .button:focus-visible{' . implode( ';', $decls ) . ';outline:2px solid currentColor;outline-offset:2px;}'; }
		}

		self::enqueue_dynamic_css( $css );

		return $html;
	}
}

