	/**
	 * Add data-xsb-r="<token>" to the block's first element tag.
	 *
	 * @param string $html  Rendered block HTML.
	 * @param string $token Token.
	 * @return string|false HTML with the attribute, or false when the first
	 *                      tag cannot be identified safely.
	 */
	private static function tag_responsive_token( $html, $token ) {
		$pos = strpos( $html, '<' );
		if ( false === $pos ) {
			return false;
		}
		$end = strpos( $html, '>', $pos );
		if ( false === $end ) {
			return false;
		}
		$tag = substr( $html, $pos, $end - $pos + 1 );
		if ( ! preg_match( '/^<[a-zA-Z][a-zA-Z0-9]*([\s>])/', $tag ) ) {
			return false;
		}
		$attr = ' data-xsb-r="' . esc_attr( $token ) . '"';
		if ( strpos( $tag, '/>' ) !== false && ! preg_match( '/\s\/>$/', $tag ) ) {
			$new_tag = preg_replace( '/\/>$/', $attr . ' />', $tag );
		} elseif ( substr( $tag, - 1 ) === '>' ) {
			$new_tag = substr( $tag, 0, - 1 ) . $attr . '>';
		} else {
			return false;
		}
		return substr_replace( $html, $new_tag, $pos, strlen( $tag ) );
	}

	/**
	 * Whether a block's root element is its first rendered tag (so a desktop
	 * transform can be injected centrally). Blocks that opt out via
	 * root_unprefixed => false render an optional element first (e.g. the
	 * ordering title) and style their root with a dedicated selector.
	 *
	 * @param string $type Block type.
	 * @return bool
	 */
	private static function transform_root_first_tag( $type ) {
		$inner = self::responsive_inner_map();
		if ( empty( $inner[ $type ] ) ) {
			return true;
		}
		foreach ( $inner[ $type ] as $entry ) {
			if ( isset( $entry['root_unprefixed'] ) && false === $entry['root_unprefixed'] ) {
				return false;
			}
		}
		return true;
	}

	/**
	 * Apply a block's Advanced settings (CSS class / HTML id) to its rendered
	 * output. Returns the HTML untouched when no Advanced value is set.
	 *
	 * @param string $html     Rendered block HTML.
	 * @param array  $settings Block settings.
	 * @return string
	 */
	public static function apply_advanced( $html, $settings ) {
		if ( '' === $html || ! is_array( $settings ) ) {
			return $html;
		}

		$raw_class = isset( $settings['css_class'] ) ? trim( (string) $settings['css_class'] ) : '';
		$id        = isset( $settings['css_id'] ) ? trim( (string) $settings['css_id'] ) : '';

		if ( '' === $raw_class && '' === $id ) {
			return $html;
		}

		$classes = array( 'xsb-advanced-block' );
		if ( '' !== $raw_class ) {
			// One or more classes, each sanitised separately.
			$tokens = preg_split( '/\s+/', $raw_class );
			foreach ( $tokens as $token ) {
				$token = sanitize_html_class( $token );
				if ( '' !== $token ) {
					$classes[] = $token;
				}
			}
		}

		$out  = '<div class="' . esc_attr( implode( ' ', array_unique( $classes ) ) ) . '"';
		if ( '' !== $id ) {
			$out .= ' id="' . esc_attr( sanitize_html_class( $id ) ) . '"';
		}
		$out .= '>' . $html . '</div>';

		return $out;
	}

