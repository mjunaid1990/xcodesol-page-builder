	/**
	 * Queue inline front-end JavaScript on the shared plugin handle.
	 *
	 * Behavior that used to live in inline `on*` attributes is stripped by
	 * escaping, so small snippets are attached to a file-less script handle
	 * instead (printed in the footer, like any enqueued script).
	 *
	 * @param string $code JavaScript source.
	 * @return void
	 */
	public static function add_frontend_script( $code ) {
		$code = trim( (string) $code );

		if ( '' === $code ) {
			return;
		}

		if ( ! wp_script_is( self::FRONTEND_SCRIPT, 'registered' ) ) {
			wp_register_script( self::FRONTEND_SCRIPT, false, array(), XCOPB_VERSION, true );
		}

		wp_enqueue_script( self::FRONTEND_SCRIPT );
		wp_add_inline_script( self::FRONTEND_SCRIPT, $code );
	}

	/**
	 * Register a block type.
	 *
	 * Extension point: add new block types by calling this method.
	 *
	 * @param string $type            Block type identifier (e.g., 'xcosb/sp-title').
	 * @param callable $render_callback Callback function( array $block, array $context ): string.
	 * @param array  $defaults        Default settings for the block.
	 */
	public function register_block( $type, $render_callback, $defaults = array() ) {
		$this->blocks[ $type ] = array(
			'callback' => $render_callback,
			'defaults' => $defaults,
		);
	}

	/**
	 * Render a block.
	 *
	 * @param string $type    Block type.
	 * @param array  $block   Block data with settings.
	 * @param array  $context Context data.
	 * @return string Rendered HTML.
	 */
	public function render_block( $type, $block, $context = array() ) {
		if ( ! isset( $this->blocks[ $type ] ) ) {
			$alt_type = str_replace( array( 'xcosb/', 'xsb/', 'wtb/' ), 'xcopb/', $type );
			if ( isset( $this->blocks[ $alt_type ] ) ) {
				$type = $alt_type;
			}
		}
		if ( ! isset( $this->blocks[ $type ] ) ) {
			return '';
		}

		$handler = $this->blocks[ $type ];
		$settings = isset( $block['settings'] ) ? $block['settings'] : array();
		$settings = wp_parse_args( $settings, $handler['defaults'] );

		$merged_block = array(
			'type'     => $type,
			'settings' => $settings,
		);

		if ( isset( $block['inner'] ) && is_array( $block['inner'] ) ) {
			$merged_block['inner'] = $block['inner'];
		}

		$html = call_user_func( $handler['callback'], $merged_block, $context );

		$html = self::apply_advanced( $html, $settings );

		// Desktop transform rides the block root's first tag unless the type
		// declares otherwise (ordering's first tag may be its optional title).
		if ( self::transform_root_first_tag( $type ) ) {
			$html = self::apply_transform_root( $html, $settings );
		}

		$html = self::apply_responsive( $type, $html, $settings );

		return self::apply_interaction( $type, $html, $settings );
	}

