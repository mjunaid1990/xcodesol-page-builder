	/**
	 * Queue sanitized dynamic CSS on the public stylesheet.
	 *
	 * @param string $css CSS generated by this plugin.
	 * @return void
	 */
	private static function enqueue_dynamic_css( $css ) {
		$css = trim( wp_strip_all_tags( (string) $css ) );

		if ( '' === $css ) {
			return;
		}

		if ( ! wp_style_is( 'xcopb-public', 'registered' ) ) {
			wp_register_style( 'xcopb-public', XCOPB_PLUGIN_URL . 'assets/public/xpb-styles.css', array(), XCOPB_VERSION );
		}

		wp_enqueue_style( 'xcopb-public' );
		wp_add_inline_style( 'xcopb-public', $css );
	}

	/**
	 * Get instance.
	 *
	 * @return XCOPB_Block_Registry
	 */
	public static function instance() {
		if ( null === self::$instance ) {
			self::$instance = new self();
		}
		return self::$instance;
	}

	/**
	 * Constructor.
	 */
	private function __construct() {
		// Inline styles carry animations, transitions, order and text shadows
		// for the widget styling layer. WordPress' default safe-CSS list leaves
		// those out, which would silently drop them when the rendered template
		// is escaped with kses() on output.
		add_filter( 'safe_style_css', array( __CLASS__, 'safe_style_css' ) );
	}

	/**
	 * Allow the CSS properties the builder emits in inline styles.
	 *
	 * @param string[] $props Safe CSS property names.
	 * @return string[]
	 */
