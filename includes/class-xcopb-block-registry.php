	/**
	 * Turn one settings key + value into a CSS declaration value.
	 *
	 * @param string $key   Base settings key.
	 * @param mixed  $value Stored value.
	 * @return string CSS value ('' when the key is not responsive-capable).
	 */
	public static function responsive_css_value( $key, $value ) {
		if ( 'opacity' === $key ) {
			if ( '' === $value || null === $value ) {
				return '';
			}
			return sprintf( '%.2f', min( 100, max( 0, absint( $value ) ) ) / 100 );
		}

		$map = self::responsive_root_keys();
		if ( ! isset( $map[ $key ] ) || '' === $value || null === $value ) {
			return '';
		}
		$type = $map[ $key ];
		if ( 'px' === $type ) {
			$n = absint( $value );
			return $n > 0 ? $n . 'px' : '';
		}
		if ( 'float' === $type ) {
			$n = (float) $value;
			return $n > 0 ? (string) $n : '';
		}
		if ( 'shadow' === $type ) {
			return self::shadow_css( (string) $value );
		}
		$clean = trim( (string) $value );
		return '' === $clean ? '' : $clean;
	}

